-- Secventa autoincrement
CREATE SEQUENCE SEQ_ANGAJATI
START WITH 1
INCREMENT BY 1
NOCACHE
NOCYCLE;

-- Tabela angajati
CREATE TABLE ANGAJATI (
    NR_CRT NUMBER(10) PRIMARY KEY,
    NUME VARCHAR2(50) NOT NULL,
    PRENUME VARCHAR2(50) NOT NULL,
    FUNCTIE VARCHAR2(50) NOT NULL,
    SALAR_BAZA NUMBER(10) NOT NULL CHECK (SALAR_BAZA BETWEEN 1 AND 2000000),
    SPOR_PROCENT NUMBER(6,2) DEFAULT 0 NOT NULL CHECK (SPOR_PROCENT BETWEEN 0 AND 1000),
    PREMII_BRUTE NUMBER(10) DEFAULT 0 NOT NULL CHECK (PREMII_BRUTE BETWEEN 0 AND 1000000),
    RETINERI NUMBER(10) DEFAULT 0 NOT NULL CHECK (RETINERI BETWEEN 0 AND 1000000),
    TOTAL_BRUT NUMBER(10) DEFAULT 0 NOT NULL,
    CAS NUMBER(10) DEFAULT 0 NOT NULL,
    CASS NUMBER(10) DEFAULT 0 NOT NULL,
    BRUT_IMPOZABIL NUMBER(10) DEFAULT 0 NOT NULL,
    IMPOZIT NUMBER(10) DEFAULT 0 NOT NULL,
    VIRAT_CARD NUMBER(10) DEFAULT 0 NOT NULL,
    POZA BLOB
);

-- Trigger ID
CREATE OR REPLACE TRIGGER TRG_ANGAJATI_BI
BEFORE INSERT ON ANGAJATI
FOR EACH ROW
BEGIN
    IF :NEW.NR_CRT IS NULL OR :NEW.NR_CRT = 0 THEN
        SELECT SEQ_ANGAJATI.NEXTVAL INTO :NEW.NR_CRT FROM DUAL;
    END IF;
END;
/

-- Trigger calcul salarii
CREATE OR REPLACE TRIGGER TRG_CALCUL_SALARIU_ROW
BEFORE INSERT OR UPDATE ON ANGAJATI
FOR EACH ROW
DECLARE
    v_cas_p NUMBER;
    v_cass_p NUMBER;
    v_imp_p NUMBER;
BEGIN
    BEGIN
        SELECT CAS_PROCENT, CASS_PROCENT, IMPOZIT_PROCENT
        INTO v_cas_p, v_cass_p, v_imp_p
        FROM PARAMETRI_TAXE
        WHERE ID = 1;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            v_cas_p := 25.0;
            v_cass_p := 10.0;
            v_imp_p := 10.0;
    END;

    :NEW.TOTAL_BRUT := ROUND(:NEW.SALAR_BAZA * (1 + NVL(:NEW.SPOR_PROCENT, 0) / 100) + NVL(:NEW.PREMII_BRUTE, 0));
    :NEW.CAS := ROUND(:NEW.TOTAL_BRUT * (v_cas_p / 100));
    :NEW.CASS := ROUND(:NEW.TOTAL_BRUT * (v_cass_p / 100));
    :NEW.BRUT_IMPOZABIL := ROUND(:NEW.TOTAL_BRUT - :NEW.CAS - :NEW.CASS);
    :NEW.IMPOZIT := ROUND(:NEW.BRUT_IMPOZABIL * (v_imp_p / 100));
    :NEW.VIRAT_CARD := ROUND(:NEW.TOTAL_BRUT - :NEW.IMPOZIT - :NEW.CAS - :NEW.CASS - NVL(:NEW.RETINERI, 0));
END;
/

-- Triggerul de salariu recalculeaza toate campurile calculate la orice UPDATE.
-- Procedura forteaza recalcularea, iar aplicatia controleaza COMMIT/ROLLBACK.
CREATE OR REPLACE PROCEDURE PROC_RECALCULARE_SALARII AS
BEGIN
    UPDATE ANGAJATI SET SALAR_BAZA = SALAR_BAZA;
END;
/

COMMIT;
