CREATE TABLE PARAMETRI_TAXE (
    ID NUMBER(2) DEFAULT 1 PRIMARY KEY CHECK (ID = 1),
    CAS_PROCENT NUMBER(5,2) DEFAULT 25.00 NOT NULL CHECK (CAS_PROCENT BETWEEN 0 AND 100),
    CASS_PROCENT NUMBER(5,2) DEFAULT 10.00 NOT NULL CHECK (CASS_PROCENT BETWEEN 0 AND 100),
    IMPOZIT_PROCENT NUMBER(5,2) DEFAULT 10.00 NOT NULL CHECK (IMPOZIT_PROCENT BETWEEN 0 AND 100),
    PAROLA VARCHAR2(100) DEFAULT '9662720154e020e7f58939342b8a06f918c8cc53e9408007ffc3ed1a7493bf1c' NOT NULL CHECK (LENGTH(PAROLA) = 64)
);

