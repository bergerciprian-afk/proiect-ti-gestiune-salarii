-- Ruleaza cu SYSTEM conectat la serviciul XEPDB1.
SET ECHO OFF
SET VERIFY OFF
SET DEFINE ON
WHENEVER OSERROR EXIT FAILURE ROLLBACK
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

BEGIN
    IF SYS_CONTEXT('USERENV', 'CON_NAME') <> 'XEPDB1' THEN
        RAISE_APPLICATION_ERROR(-20001, 'Conecteaza-te la serviciul XEPDB1.');
    END IF;
END;
/

ACCEPT parole_oracle CHAR PROMPT 'Alege parola pentru TI_SALARII (litere si cifre): ' HIDE
CREATE USER TI_SALARII IDENTIFIED BY "&parole_oracle"
    DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE TRIGGER,
      CREATE PROCEDURE TO TI_SALARII;

CONNECT TI_SALARII/"&parole_oracle"@localhost:1521/XEPDB1
UNDEFINE parole_oracle

@@01_creare_schema_si_tabele.sql
@@02_populare_date_test.sql

PROMPT Configurare finalizata pentru TI_SALARII.
EXIT SUCCESS
